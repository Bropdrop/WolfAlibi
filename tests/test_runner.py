"""Execution and compatibility tests; every executable here is SYNTHETIC.

The successful report is deliberately a simulator. It proves wrapper behavior,
never TPM verification or genuine upstream compatibility.
"""

from __future__ import annotations

import copy
import hashlib
import json
import os
from pathlib import Path
import sys
import tempfile
import time
import unittest
from unittest import mock

from shirudo_adapter.model import AdapterError, UPSTREAM_COMMIT, canonical_json
from shirudo_adapter.runner import run_verifier


VERSION = "a" * 64
NONCE = "b" * 64
EVIDENCE = canonical_json({"schema": 1, "kind": "shirudo-attestation", "nonce": NONCE})

# Transcribed from the pinned util/attest.c success path, not generated by
# runner._BASE_CHECKS. Changes to the upstream labels need a source review.
LABELS = (
    "nonce matches the request",
    "attestation key: restricted, fixed to this TPM",
    "attestation key: name matches its public area",
    "attestation key: the pinned key",
    "endorsement key: name matches its public area",
    "endorsement key: TCG default template under the endorsement policy",
    "endorsement key: the pinned key",
    "quote: ECDSA signature by the attestation key",
    "quote: signed by the key as an endorsement primary",
    "quote: carries the nonce",
    "quote: covers the PCRs the document lists",
    "quote: PCR digest matches the listed values",
    "register: ECDSA signature by the attestation key",
    "register: signed by the key as an endorsement primary",
    "register: carries the nonce",
    "register: certification names the listed index",
    "register: certified contents match the listed value",
    "quote and certification are of one TPM boot",
    "config: config root history matches the quoted PCR",
    "eventlog: this boot has an init record",
    "register: the document names index 0x01818E00 and PCRs 9 and 11",
    "register: public area is bound to PCRs 9 and 11 as recorded",
    "binding: PCR 9 held the expected value",
    "binding: PCR 11 held the expected value",
    "binding: made while the initrd ran",
    "eventlog: one init record for this TPM reset (1 this boot)",
    "register: init record is of the TPM's current reset count",
    "eventlog: 1 record replay to the certified value",
    "anchor: record digest matches the index name",
    "anchor: PCR 9 equals the recorded value extended by the anchor",
    "state: register equals the expected value",
    "PCR 7 matches the expected value",
)


def report() -> dict:
    return {"schema": 1, "verdict": "ok", "checks": [
        {"result": "ok", "text": label} for label in LABELS
    ]}


@unittest.skipUnless(sys.platform == "linux" and hasattr(os, "memfd_create"), "requires Linux memfd")
class RunnerTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="wolfalibi-runner-test-")
        self.addCleanup(self.temp.cleanup)
        self.directory = Path(self.temp.name)
        self.executable = self.directory / "synthetic-verifier"

    def fixture(self, response=None, *, exit_code=0, body="", version=VERSION, version_body="", config_nvpcr=False):
        response = report() if response is None else response
        config_flag = "--expect-config-nvpcr=000b" + "6" * 64 if config_nvpcr else "--expect-config-pcr=14"
        source = f'''#!{sys.executable}
import errno, fcntl, json, os, sys, time
if sys.argv[1:] == ["version", "--version-id"]:
    {version_body or "pass"}
    print({version!r})
    raise SystemExit(0)
assert sys.argv[1:3] == ["attest", "verify"]
assert "WOLFALIBI_SENTINEL" not in os.environ
assert "--require-initrd" in sys.argv and "--json" in sys.argv
assert not any("allow-runtime" in a or "strict-anchor" in a or "trust-presented" in a for a in sys.argv)
expected_args = {{
    "--nonce={NONCE}", "--ak-name=000b" + "1" * 64,
    "--ek-name=000b" + "2" * 64, "--expect-chain=" + "3" * 64,
    "--expect-bind-pcr=9=" + "0" * 64, "--expect-bind-pcr=11=" + "0" * 64,
    "--expect-config-root=" + "4" * 64, {config_flag!r},
    "--expect-pcr=7=" + "5" * 64,
}}
assert expected_args.issubset(set(sys.argv))
assert len(sys.argv) == len(expected_args) + 6
evidence_path = next(a.split("=", 1)[1] for a in sys.argv if a.startswith("--evidence="))
for path in (sys.argv[0], evidence_path):
    fd = os.dup(int(path.rsplit("/", 1)[1]))
    seals = 0x0001 | 0x0002 | 0x0004 | 0x0008
    assert fcntl.fcntl(fd, 1034) & seals == seals
    try:
        os.write(fd, b"x")
    except OSError as exc:
        assert exc.errno == errno.EPERM
    else:
        raise AssertionError("snapshot is writable")
    os.close(fd)
with open(evidence_path, "rb") as source:
    assert source.read() == {EVIDENCE!r}
{body or "pass"}
print({json.dumps(response, separators=(",", ":"))!r})
raise SystemExit({exit_code})
'''
        self.executable.write_text(source)
        self.executable.chmod(0o700)
        self.policy = {
            "schema": "wolfalibi.shirudo.policy.v1", "policy_id": "synthetic-test",
            "target_id": "synthetic-fixture", "assurance": "SYNTHETIC",
            "enrollment": {"method": "synthetic_fixture", "record_sha256": "e" * 64,
                           "ak_name": "000b" + "1" * 64, "ek_name": "000b" + "2" * 64},
            "expected": {"chain": "3" * 64, "config_root": "4" * 64, "config_pcr": 14,
                         "binding_pcrs": {"9": "0" * 64, "11": "0" * 64},
                         "quote_pcrs": {"7": "5" * 64}},
            "verifier": {"source_commit": UPSTREAM_COMMIT,
                         "sha256": hashlib.sha256(source.encode()).hexdigest(),
                         "version_id": VERSION, "timeout_seconds": 2},
            "challenge_ttl_seconds": 60,
        }
        if config_nvpcr:
            self.policy["expected"].pop("config_pcr")
            self.policy["expected"]["config_nvpcr"] = "000b" + "6" * 64

    def run_fixture(self):
        return run_verifier(str(self.executable), EVIDENCE, self.policy, NONCE)

    def assert_error(self, code):
        with self.assertRaises(AdapterError) as caught:
            self.run_fixture()
        self.assertEqual(caught.exception.code, code)

    def test_success_checks_exact_arguments_and_both_immutable_fds(self):
        self.fixture()
        with mock.patch.dict(os.environ, {"WOLFALIBI_SENTINEL": "must-not-reach-verifier"}):
            result = self.run_fixture()
        self.assertTrue(result["accepted"])
        self.assertEqual(result["execution_profile"], "SYNTHETIC")
        self.assertEqual(result["binary_sha256"], self.policy["verifier"]["sha256"])
        self.assertEqual(result["version_id"], VERSION)

    def test_replacing_source_after_version_cannot_replace_executed_bytes(self):
        mutation = f"open({str(self.executable)!r}, 'wb').write(b'not the verifier anymore')"
        self.fixture(version_body=mutation)
        self.assertTrue(self.run_fixture()["accepted"])
        self.assertEqual(self.executable.read_bytes(), b"not the verifier anymore")

    def test_authentic_early_failure_is_a_rejected_result(self):
        self.fixture({"schema": 1, "verdict": "fail", "checks": [
            {"result": "fail", "text": "attestation key: public area is not a P-256 ECDSA key"}
        ]}, exit_code=1)
        result = self.run_fixture()
        self.assertFalse(result["accepted"])
        self.assertEqual(result["exit_code"], 1)

    def test_success_without_binding_assertion_is_blocked(self):
        value = report()
        value["checks"] = [c for c in value["checks"] if c["text"] != "binding: PCR 11 held the expected value"]
        self.fixture(value)
        self.assert_error("VERIFIER_ASSERTIONS")

    def test_supported_anchor_note_does_not_claim_log_replay(self):
        value = report()
        anchor = next(c for c in value["checks"] if c["text"].startswith("anchor: PCR 9 equals"))
        anchor.update(result="note", text="anchor: PCR 9 carries further measurements after the anchor; replay the logs to confirm it")
        self.fixture(value)
        result = self.run_fixture()
        self.assertTrue(result["accepted"])
        self.assertIn(anchor, result["report"]["checks"])

    def test_nvpcr_requires_its_certification_and_operator_index_pin(self):
        value = report()
        config = next(c for c in value["checks"] if c["text"].startswith("config:"))
        config["text"] = "config: config root history matches the certified NvPCR"
        value["checks"].extend({"result": "ok", "text": "config NvPCR: " + label} for label in (
            "ECDSA signature by the attestation key", "signed by the key as an endorsement primary",
            "carries the nonce", "certified name and contents", "same TPM boot as quote",
            "the operator-pinned index",
        ))
        self.fixture(value, config_nvpcr=True)
        self.assertTrue(self.run_fixture()["accepted"])
        value["checks"] = [c for c in value["checks"] if c["text"] != "config NvPCR: the operator-pinned index"]
        self.fixture(value, config_nvpcr=True)
        self.assert_error("VERIFIER_ASSERTIONS")

    def test_counterfeit_success_reports_are_blocked(self):
        variants = []
        value = report(); value["schema"] = True; variants.append(value)
        value = report(); value["checks"][0]["result"] = False; variants.append(value)
        value = report(); value["checks"][0]["result"] = "fail"; variants.append(value)
        value = report(); value["checks"].append({"result": "ok", "text": "trust me"}); variants.append(value)
        value = report(); value["checks"].append(copy.deepcopy(value["checks"][0])); variants.append(value)
        value = report(); value["verdict"] = "fail"; variants.append(value)
        value = report(); value["unexpected"] = "field"; variants.append(value)
        for index, value in enumerate(variants):
            with self.subTest(case=index):
                self.fixture(value)
                self.assert_error("VERIFIER_REPORT")

    def test_duplicate_json_and_trailing_output_are_blocked(self):
        self.fixture(body='print(\'{"schema":1,"schema":1,"verdict":"ok","checks":[]}\'); raise SystemExit(0)')
        self.assert_error("DUPLICATE_JSON_KEY")
        self.fixture(body='print("unframed preamble")')
        self.assert_error("INVALID_JSON")

    def test_digest_version_and_source_pins(self):
        self.fixture()
        self.policy["verifier"]["sha256"] = "f" * 64
        self.assert_error("EXECUTABLE_DIGEST")
        self.fixture(version="f" * 64)
        self.assert_error("VERIFIER_VERSION")
        self.fixture()
        self.policy["verifier"]["source_commit"] = "0" * 40
        self.assert_error("UNSUPPORTED_UPSTREAM")

    def test_script_cannot_be_promoted_to_hardware_or_lab(self):
        for assurance, method in (("LAB_VTPM", "trusted_builder"), ("HARDWARE_TPM", "manufacturer_chain")):
            with self.subTest(assurance=assurance):
                self.fixture()
                self.policy["assurance"] = assurance
                self.policy["enrollment"]["method"] = method
                self.assert_error("EXECUTABLE_TYPE")

    def test_symlink_and_relative_executable_are_refused(self):
        self.fixture()
        link = self.directory / "verifier-link"
        link.symlink_to(self.executable)
        self.executable = link
        self.assert_error("EXECUTABLE_PATH")
        self.executable = Path("relative-verifier")
        self.assert_error("EXECUTABLE_PATH")

    def test_stdout_and_stderr_are_bounded_while_running(self):
        for fd in (1, 2):
            with self.subTest(fd=fd):
                self.fixture(body=f'os.write({fd}, b"x" * 1000000)')
                self.assert_error("VERIFIER_OUTPUT_LIMIT")

    def test_version_and_verification_share_one_deadline(self):
        self.fixture(version_body="time.sleep(0.6)", body="time.sleep(0.6)")
        self.policy["verifier"]["timeout_seconds"] = 1
        before = time.monotonic()
        self.assert_error("VERIFIER_TIMEOUT")
        self.assertLess(time.monotonic() - before, 2.5)

    def test_descendant_holding_output_pipes_is_killed_at_deadline(self):
        marker = self.directory / "child-pid"
        self.fixture(body=f'''child = os.fork()
if child == 0:
    open({str(marker)!r}, "w").write(str(os.getpid()))
    time.sleep(20)
    os._exit(0)
''')
        self.policy["verifier"]["timeout_seconds"] = 1
        self.assert_error("VERIFIER_TIMEOUT")
        child = int(marker.read_text())
        # A killed child may remain briefly as an init-owned zombie; it may
        # not be a running or sleeping process after group cleanup.
        status = Path(f"/proc/{child}/stat")
        deadline = time.monotonic() + 0.5
        while status.exists() and time.monotonic() < deadline:
            if status.read_text().split(") ", 1)[1][0] == "Z":
                return
            time.sleep(0.01)
        self.assertFalse(status.exists(), "verifier descendant survived process-group cleanup")

    def test_unknown_exit_does_not_become_a_rejected_or_accepted_proof(self):
        self.fixture(exit_code=2)
        self.assert_error("VERIFIER_EXIT")


if __name__ == "__main__":
    unittest.main()
